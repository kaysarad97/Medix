import 'package:flutter/widgets.dart';

/// Цветовые токены MedIx.
///
/// Значения сняты пипеткой с макетов в `design/` (440×956 pt — это ровно
/// логические точки iPhone 16 Pro Max, поэтому замеры переносятся 1:1).
/// Не подбирать на глаз: при обновлении макетов пересматривать файл целиком.
abstract final class AppColors {
  /// Самый тёмный синий бренда. Заполненная часть прогресс-бара регистрации,
  /// текстовые ссылки («или создать профиль»).
  static const Color brandIndigo = Color(0xFF0E0777);

  /// Основной CTA на экране логина («Войти»).
  static const Color primary = Color(0xFF1719C3);

  /// CTA на остальных экранах («Далее», «На главную страницу»).
  ///
  /// В макетах это осознанно другой синий, а не вариация [primary] —
  /// см. `design/Логин Старт.png` против `design/Создайте профиль.png`.
  static const Color primaryBright = Color(0xFF2162FB);

  /// Акцент: трек прогресс-бара, введённый текст в полях, точки пароля, иконки.
  static const Color accent = Color(0xFF4787FA);

  /// Подложка иконок-чипов и пилюль с датой.
  static const Color accentSoft = Color(0xFF9CCAFF);

  /// Заливка выделенных карточек («Загрузить анализы»).
  static const Color accentSofter = Color(0xFFC0DDFF);

  /// Серая карточка — форма логина, поле поиска на главной.
  static const Color surface = Color(0xFFF3F3F3);

  /// Белая поверхность — поля ввода, карточки врачей.
  static const Color surfaceWhite = Color(0xFFFCFDFE);

  /// Голубая информационная карточка («Найти лабораторию или больницу»).
  static const Color surfaceInfo = Color(0xFFE6F3FE);

  /// Заголовки и основной текст.
  static const Color textPrimary = Color(0xFF212528);

  // ОСОЗНАННОЕ РАСХОЖДЕНИЕ С МАКЕТОМ. Подписи полей на `Логин Старт.png`
  // залиты #17371D — тёмно-зелёным. На макете шириной 440 он читается как
  // почти чёрный, но на реальном экране рядом с нейтральным #212528 он
  // откровенно зелёный (проверено скриншотом с устройства). Больше нигде
  // в `design/` этого цвета нет: он встречается ровно дважды, на двух
  // подписях одного экрана. Признано ошибкой макета, подписи переведены
  // на textPrimary. Токена textLabel намеренно не существует.

  /// Плейсхолдеры, вторичные иконки.
  static const Color textSecondary = Color(0xFF797B7E);

  /// Подзаголовки поверх градиентного фона («Подтвердите личность»).
  static const Color textMuted = Color(0xFF626E7D);

  /// Текст на залитых кнопках.
  static const Color textOnPrimary = Color(0xFFFCFDFE);

  static const Color divider = Color(0xFFE3E3E4);

  /// ВНЕ МАКЕТОВ. В `design/` цвета ошибки нет: экран «Оплата НЕ прошла»
  /// использует тот же брендовый синий, а состояние передаётся иконкой и
  /// текстом. Для инлайн-валидации форм этого недостаточно, поэтому токен
  /// добавлен нами. Требует утверждения дизайнером.
  static const Color error = Color(0xFFD64550);

  /// Тень карточек. Профиль замерен по спаду яркости вокруг карточки
  /// в `design/Логин Старт.png`: ~7 px вниз, ~4 px вбок, пик α ≈ 0.20.
  static const Color shadow = Color(0x33000000);
}

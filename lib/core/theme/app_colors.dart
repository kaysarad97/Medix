import 'package:flutter/widgets.dart';

/// Цветовые токены MedIx.
///
/// Значения сняты пипеткой с макетов в `design/` (440×956 pt — это ровно
/// логические точки iPhone 16 Pro Max, поэтому замеры переносятся 1:1).
/// Не подбирать на глаз: при обновлении макетов пересматривать файл целиком.
abstract final class AppColors {
  /// Самый тёмный синий бренда. Заполненная часть прогресс-бара регистрации,
  /// текстовые ссылки («или создать профиль»).
  static const Color brandIndigo = Color(0xFF0E0777);

  /// Основной CTA на экране логина («Войти»).
  static const Color primary = Color(0xFF1719C3);

  /// CTA на остальных экранах («Далее», «На главную страницу»).
  ///
  /// В макетах это осознанно другой синий, а не вариация [primary] —
  /// см. `design/Логин Старт.png` против `design/Создайте профиль.png`.
  static const Color primaryBright = Color(0xFF2162FB);

  /// Акцент: трек прогресс-бара, введённый текст в полях, точки пароля, иконки.
  static const Color accent = Color(0xFF4787FA);

  /// Подложка иконок-чипов и пилюль с датой.
  static const Color accentSoft = Color(0xFF9CCAFF);

  /// Заливка выделенных карточек («Загрузить анализы»).
  static const Color accentSofter = Color(0xFFC0DDFF);

  /// Серая карточка — форма логина, поле поиска на главной.
  static const Color surface = Color(0xFFF3F3F3);

  /// Белая поверхность — поля ввода, карточки врачей.
  static const Color surfaceWhite = Color(0xFFFCFDFE);

  /// Голубая информационная карточка («Найти лабораторию или больницу»).
  static const Color surfaceInfo = Color(0xFFE6F3FE);

  /// Подложка чипа города в шапке врача (`design/Профиль врача + запись.png`).
  ///
  /// Светлее [accentSofter] на 14 уровней по красному. Чип лежит на синем
  /// градиенте — похоже на белый с прозрачностью, а не на отдельный цвет.
  /// Уточнить у дизайнера при следующем обновлении макетов.
  static const Color surfaceChip = Color(0xFFCEE5FD);

  /// Недоступный элемент: колонка выходного дня в расписании врача.
  static const Color surfaceDisabled = Color(0xFFC9C9CA);

  /// Подложка переключателя вкладок над списком анализов.
  static const Color surfaceToggle = Color(0xFFCBE5FE);


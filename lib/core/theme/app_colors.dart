  // границей нормы, норма, за верхней. Цвета сняты пипеткой и намеренно
  // не сведены к общей палитре: это единственное место, где смысл несёт
  // сам цвет, и подгонять его под бренд нельзя.

  /// Ниже нормы.
  static const Color scaleLow = Color(0xFFD5AF46);

  /// Норма.
  static const Color scaleNormal = Color(0xFF449D2B);

  /// Выше нормы.
  static const Color scaleHigh = Color(0xFFCD4023);

  /// Заголовки и основной текст.
  static const Color textPrimary = Color(0xFF212528);

  // ОСОЗНАННОЕ РАСХОЖДЕНИЕ С МАКЕТОМ. Подписи полей на `Логин Старт.png`
  // залиты #17371D — тёмно-зелёным. На макете шириной 440 он читается как
  // почти чёрный, но на реальном экране рядом с нейтральным #212528 он
  // откровенно зелёный (проверено скриншотом с устройства). Больше нигде
  // в `design/` этого цвета нет: он встречается ровно дважды, на двух
  // подписях одного экрана. Признано ошибкой макета, подписи переведены
  // на textPrimary. Токена textLabel намеренно не существует.

  /// Плейсхолдеры, вторичные иконки.
  static const Color textSecondary = Color(0xFF797B7E);

  /// Подзаголовки поверх градиентного фона («Подтвердите личность»).
  static const Color textMuted = Color(0xFF626E7D);

  /// Текст недоступного элемента: число выходного дня в расписании.
  static const Color textDisabled = Color(0xFFA4A7A8);

  /// Текст на залитых кнопках.
  static const Color textOnPrimary = Color(0xFFFCFDFE);

  static const Color divider = Color(0xFFE3E3E4);

  /// ВНЕ МАКЕТОВ. В `design/` цвета ошибки нет: экран «Оплата НЕ прошла»
  /// использует тот же брендовый синий, а состояние передаётся иконкой и
  /// текстом. Для инлайн-валидации форм этого недостаточно, поэтому токен
  /// добавлен нами. Требует утверждения дизайнером.
  static const Color error = Color(0xFFD64550);

  /// Тень карточек. Профиль замерен по спаду яркости вокруг карточки
  /// в `design/Логин Старт.png`: ~7 px вниз, ~4 px вбок, пик α ≈ 0.20.
  static const Color shadow = Color(0x33000000);
}

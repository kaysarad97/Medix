/// Работать против заглушек вместо реального API.
///
/// Бэкенд готов не целиком: авторизация, профиль, семья и каталог врачей
/// живые, а подписки, звонки, лаборатории и чаты отвечают заглушкой
/// `{"status": "scaffolded"}`. Поэтому флаг общий: он переключает разом все
/// разделы, у которых есть боевая реализация, и не трогает те, где её нет.
///
/// По умолчанию приложение ходит в настоящий API. Заглушки включаются на
/// время работы без поднятого сервера:
/// `flutter run --dart-define=MEDIX_USE_MOCKS=true`
///
/// Живёт в `core/`, а не в провайдерах авторизации, где стоял раньше: флаг
/// понадобился второй фиче, а импортировать провайдеры одной фичи из другой
/// нельзя.
const bool useMocks = bool.fromEnvironment('MEDIX_USE_MOCKS');
